namespace PetTemplate.Services.Assistant;

/// <summary>
/// Контекст хода (спец. assistant, разделы 9 и 10): от чьего имени, в каком
/// пространстве и относительно какого «сейчас» работают инструменты.
///
/// Scoped-класс, а не параметры каждого инструмента: схемы инструментов должны
/// оставаться плоскими и короткими (16.5), а <c>userId</c> и пространство модели
/// не показывают вовсе — иначе их можно было бы подменить строкой в чужом тексте.
///
/// Заполняет его обработчик хода из записи прогона, которая помнит зону и язык
/// на момент просьбы.
/// </summary>
public class AssistantContext
{
    public Guid UserId { get; set; }

    public Guid WorkspaceId { get; set; }

    /// <summary>
    /// Строка IANA (<c>Europe/Moscow</c>) из заголовка <c>X-Time-Zone</c>.
    /// Неизвестная строка — это UTC и запись в логах, а не отказ запроса (раздел 10)
    /// </summary>
    public string TimeZone { get; set; } = "UTC";

    /// <summary>
    /// Момент старта хода. Внутри одного хода «сейчас» одно, иначе десятиминутная
    /// работа разъедется сама с собой
    /// </summary>
    public DateTime NowUtc { get; set; }

    /// <summary>
    /// Сегодняшний день в зоне человека — то, относительно чего разрешаются
    /// «завтра» и «в пятницу»
    /// </summary>
    public DateOnly Today { get; set; }

    /// <summary>
    /// Реплика человека, с которой начался ход. На ней держится защита
    /// <c>remember_fact</c>: факт записывается, только если его ключ прозвучал
    /// в словах человека, а не в результате инструмента, а у общего факта и текст —
    /// его словами (12.5, раздел 9)
    /// </summary>
    public string UserText { get; set; } = string.Empty;

    /// <summary>
    /// Прогон — чтобы план помнил, каким ходом собран (12.2.1), а факт — откуда взялся (12.5)
    /// </summary>
    public Guid RunId { get; set; }

    /// <summary>
    /// Язык интерфейса автора: уезжает в системный промпт требованием к языку ответа
    /// </summary>
    public string Language { get; set; } = "ru";
}
