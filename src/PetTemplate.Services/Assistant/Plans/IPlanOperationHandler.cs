using System.Text.Json;
using PetTemplate.Shared.Enums;

namespace PetTemplate.Services.Assistant.Plans;

/// <summary>
/// Операция плана — точка расширения раздела проекта (спец. assistant, 7.1).
///
/// В ядре пишущих инструментов нет: шаблон не знает, что в проекте будут задачи или
/// заметки. Раздел, которому нужна запись через ассистента, приносит две вещи —
/// инструмент, складывающий операцию в план (<c>IAssistantToolSource</c>), и вот этот
/// обработчик, который её исполнит после согласия. Всё остальное — копилка,
/// предохранители раздела 8, согласие 5.1, сверка 5.4, идемпотентность — общее
/// и раздела не касается.
///
/// Регистрация — <c>AddPlanOperation&lt;T&gt;()</c>. Проще всего унаследовать
/// <see cref="PlanOperationHandler{TArgs}"/>: он разбирает аргументы и задаёт
/// осторожные умолчания.
/// </summary>
public interface IPlanOperationHandler
{
    /// <summary>
    /// Вид операции — строка в JSON плана (<c>PlanOperation.Kind</c>). Уезжает в базу
    /// и клиенту, поэтому не переименовывается: план, показанный вчера, применяется сегодня
    /// </summary>
    string Kind { get; }

    /// <summary>
    /// Создаёт новую сущность. Такие идут в потолок двадцати дел на план (раздел 8)
    /// и в счёт немедленного применения
    /// </summary>
    bool IsCreating { get; }

    /// <summary>
    /// Можно ли применить, не показав (5.1). Список разрешённого закрытый: всё, что
    /// разрушает или придумано ассистентом (рамка из нескольких дел, удаление, откат),
    /// отвечает <c>false</c>, и такой план идёт через «делаем?» всегда
    /// </summary>
    bool CanApplyImmediately { get; }

    /// <summary>
    /// Свой потолок операций этого вида в одном плане — «рамка одна на план»,
    /// «за раз не больше N правок». <c>null</c> — только общий потолок раздела 8
    /// </summary>
    int? MaxPerPlan { get; }

    /// <summary>
    /// На операции каких видов эта может сослаться ссылкой <c>"#n"</c> в поле
    /// <c>…Link</c>: страница — на свою книгу, задача — на свой эпик. Пусто —
    /// ссылок у операции нет
    /// </summary>
    IReadOnlyCollection<string> Frames { get; }

    /// <summary>
    /// Права, нужные операции, — тот же набор, что стоит на эндпоинте раздела
    /// (раздел 9). Проверяются живыми данными при применении, а не при сборке:
    /// право отбирают и между показом плана и словом «да» (5.4). Пусто — «участник
    /// пространства»
    /// </summary>
    IReadOnlyList<PermissionEnum> Permissions { get; }

    /// <summary>
    /// Какую существующую сущность правит операция — её идентификатор строкой.
    /// По нему потолок немедленного применения считает сущности, а не операции:
    /// десять правок одной записи — это всё ещё одна запись. У создания — <c>null</c>
    /// </summary>
    string? Target(JsonElement args);

    /// <summary>
    /// Сверка с базой перед применением (5.4): одно «да» или «нет» на запрос —
    /// жива ли целевая запись, не разъехалось ли её состояние с показанным, не прошла
    /// ли дата. <c>null</c> — всё сходится; строка — расхождение для модели, и тогда
    /// не применяется ни одна операция плана
    /// </summary>
    Task<string?> Check(JsonElement args, AssistantContext context, CancellationToken ct);

    /// <summary>
    /// Исполнить операцию. Ссылки <c>"#n"</c> к этому моменту уже заменены настоящими
    /// идентификаторами. Возвращает идентификатор созданного (или изменённого) строкой —
    /// на него сошлются следующие операции и отчёт «Готово».
    ///
    /// Отказ сервиса — <c>NotFoundException</c>, <c>BadRequestException</c>,
    /// <c>ConflictException</c> — становится крестиком у этой операции, а не падением
    /// плана (5.1); любое другое исключение — сбой инфраструктуры, и ход повторит очередь
    /// </summary>
    Task<string> Apply(JsonElement args, AssistantContext context, CancellationToken ct);
}
