using PetTemplate.Shared.Dto.Assistant;

namespace PetTemplate.Services.Assistant.Plans;

/// <summary>
/// Нужно ли человеку прочитать план до того, как он исполнится (спец. assistant, 5.1).
///
/// Вопрос «делаем?» защищает не от всего подряд, а от <b>решения, которое принял
/// ассистент</b>: выбранной даты, придуманной рамки, записи, найденной по описанию.
/// Там, где ассистент ничего не решал, переспрашивать нечего: человек только что это
/// сказал, читать ему нечего, а ритуальное «да» учит отвечать «да» не читая,
/// и в тот день, когда план будет из двадцати строк, он ответит так же.
///
/// Считать «решал или нет» по числу операций нельзя: два названных дела — это
/// две операции без единого решения, а «спланируй поездку» — одна рамка, в которой
/// решение целиком. Поэтому здесь закрытый список того, что <b>по форме</b> требует
/// чтения (<see cref="IPlanOperationHandler.CanApplyImmediately"/>), и потолок:
/// всё, для чего нужна модель, решает модель — просто не зовя <c>apply_plan</c>.
///
/// Разделение обязанностей то же, что у всей фичи: <b>код очерчивает, что вообще
/// можно применить сразу, модель решает — надо ли</b>. Модель может отказаться
/// от немедленного применения когда угодно; разрешить себе то, что здесь запрещено,
/// она не может никак.
/// </summary>
public static class PlanConsent
{
    /// <summary>
    /// Почему этот план нельзя применить, не показав. <c>null</c> — можно.
    /// </summary>
    /// <param name="operations">Операции, собранные инструментами этого хода</param>
    /// <param name="registry">Реестр операций — у каждой своё «можно ли сразу»</param>
    /// <param name="limit">
    /// Потолок затронутых сущностей, новых и изменённых, — <c>AssistantOptions.ImmediateLimit</c>
    /// (раздел 17). Пять дел в одной фразе человек ещё держит в голове, а на пятнадцати
    /// он уже не проверяет, что попало в список, — значит, список надо показать.
    /// Ноль выключает немедленное применение целиком
    /// </param>
    /// <returns>
    /// Причина словами — она уезжает модели результатом <c>apply_plan</c>, чтобы та
    /// не гадала, почему отказ, и закончила ход планом и вопросом
    /// </returns>
    public static string? Required(IReadOnlyList<PlanOperation> operations, PlanOperations registry, int limit)
    {
        if (operations.Count == 0) return "план пуст — собирать нечего";

        if (limit <= 0)
            return "немедленное применение выключено настройкой — покажи план и спроси «делаем?»";

        // Список разрешённого закрытый: рамку, удаление и откат человек читает до,
        // а не после, и такой план идёт через «да» всегда
        var guarded = operations.FirstOrDefault(x => registry.Find(x.Kind)?.CanApplyImmediately != true);
        if (guarded != null)
            return $"операция {guarded.Kind} сразу не применяется — покажи план и спроси «делаем?»";

        // Потолок считает затронутое — новое и изменённое: «перенеси всё» — это десятки
        // записей, которые человек по одной не называл, и список он читает до, а не после.
        // Считаются сущности, а не операции: десять правок одной записи — это всё ещё одна
        var touched = Touched(operations, registry);

        return touched > limit
            ? $"в плане {touched} новых и изменённых дел — такой список человек читает до, а не после: "
              + "закончи ход, он увидит список и ответит «делаем?»"
            : null;
    }

    private static int Touched(IReadOnlyList<PlanOperation> operations, PlanOperations registry)
    {
        var created = 0;
        var updated = new HashSet<string>(StringComparer.Ordinal);

        foreach (var operation in operations)
        {
            var handler = registry.Find(operation.Kind)!;
            if (handler.IsCreating)
            {
                created++;
                continue;
            }

            // Правка без цели — каждая сама по себе: свести их в одну сущность нечем
            updated.Add($"{operation.Kind}:{handler.Target(operation.Args) ?? "#" + operation.Index}");
        }

        return created + updated.Count;
    }
}
