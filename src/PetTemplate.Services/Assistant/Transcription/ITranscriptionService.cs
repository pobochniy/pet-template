namespace PetTemplate.Services.Assistant.Transcription;

/// <summary>
/// Расшифровка голоса (спец. assistant, 6.2).
///
/// Движок выбирается поздно и меняется моделью в конфигурации: выше этого интерфейса
/// устройство продукта от него не зависит — ни эндпоинт, ни тред, ни очередь,
/// ни команда про движок не знают.
///
/// Аудио сюда приходит потоком из запроса и никуда не сохраняется: запись живёт ровно
/// до конца расшифровки (раздел 9), в тред едет только текст.
/// </summary>
public interface ITranscriptionService
{
    /// <summary>
    /// Настроен ли движок. Проверяется раньше лимита пространства: просить подождать
    /// до завтра, когда голос всё равно не заработает, хуже, чем сказать как есть
    /// </summary>
    bool Available { get; }

    /// <param name="prompt">
    /// Подсказка распознавателю — логины участников пространства (6.2).
    /// Главная жалоба на транскрипцию русской речи лечится именно ей: имена
    /// перестают превращаться в случайные слова
    /// </param>
    Task<TranscriptionResult> Transcribe(
        Stream audio,
        string fileName,
        string contentType,
        string language,
        string? prompt,
        CancellationToken ct);
}
