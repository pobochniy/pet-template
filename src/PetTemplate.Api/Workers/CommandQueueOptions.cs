namespace PetTemplate.Api.Workers;

/// <summary>
/// Общий воркер очереди команд (<see cref="CommandQueueRegistration"/>): письма, индексация
/// поиска и всё, что не заводит своего. Значения — пакетные по умолчанию, кроме опроса
/// (у пакета 3 секунды, здесь 2 — письмо подтверждения человек ждёт, глядя в почту)
/// и аренды выборки (у пакета 10 секунд — меньше одной отправки письма на медленном SMTP)
/// </summary>
public class CommandQueueOptions
{
    /// <summary>
    /// Разбирать ли очередь в этом процессе. Выключено — команды по-прежнему ложатся
    /// в <c>local_queue</c> и ждут, обработчики остаются в контейнере, но воркеров нет:
    /// так API-тесты проверяют постановку, не давая её разобрать
    /// </summary>
    public bool Enabled { get; set; } = true;

    /// <summary>Пауза после пустой выборки — <c>IdleTimeout</c> пакета, у всех воркеров</summary>
    public TimeSpan PollInterval { get; set; } = TimeSpan.FromSeconds(2);

    /// <summary>Сколько строк общий воркер берёт за одну выборку</summary>
    public int PrefetchCount { get; set; } = 10;

    /// <summary>
    /// На сколько строка общего воркера уходит из выборки, пока её обрабатывают. Заведомо
    /// больше одной отправки письма: истёк раньше — строку взяли бы второй раз
    /// </summary>
    public TimeSpan InvisibilityTimeout { get; set; } = TimeSpan.FromMinutes(2);

    /// <summary>
    /// Потолок паузы перед повтором упавшей команды. Пауза удваивается с каждой попыткой
    /// (<see cref="CommandQueueRegistration.BackoffRetryPolicy"/>): команда, которая не пройдёт
    /// никогда (битое тело, несуществующий адрес), не долбит провайдера раз в минуту вечно,
    /// а заходит раз в час — и видна тревогой «Команда очереди не проходит»
    /// </summary>
    public TimeSpan MaxRetryAfterFailure { get; set; } = TimeSpan.FromHours(1);

    /// <summary>
    /// Сколько раз строку отдают обработчику, прежде чем бросить (<see cref="CommandQueueStorage"/>):
    /// ошибка в лог, счётчик <c>pettemplate.queue.gave_up</c>, строка остаётся в таблице
    /// отложенной насовсем. Считаются и выдачи, на которых процесс умер, не дойдя до конца.
    /// 25 при паузе до часа — около суток: письмо, упёршееся в лежащий SMTP, переживает ночь,
    /// а чанк, который эмбеддер не возьмёт никогда, не ходит к нему раз в час вечно.
    /// Свой предел у команды — <c>Add(maxAttempts: …)</c>
    /// </summary>
    public int MaxAttempts { get; set; } = 25;
}
