namespace PetTemplate.Shared.Enums;

/// <summary>
/// Куда упёрся диалог — по мнению судьи автооценки (спец. admin, 16.3). Не то же,
/// что <see cref="AssistantStopReason"/>: тот пишет сам ход и знает только свои
/// предохранители, а повтор одного и того же вызова видно лишь по содержимому.
/// Не упёрся ни во что — поле пустое. «Деньги» здесь нет: лимит пространства
/// проверяется до хода (спец. assistant, 13.6), и прогона у отказа не бывает.
///
/// Номера уезжают в базу — добавлять только в конец.
/// </summary>
public enum DialogStopReason
{
    /// <summary>Лимит шагов или токенов хода</summary>
    StepLimit = 0,

    /// <summary>Агент звал одно и то же по кругу</summary>
    Repetition = 1,

    /// <summary>Поставщик не ответил</summary>
    ProviderError = 2,

    /// <summary>Упёрся во что-то другое — что именно, судья пишет в заметке</summary>
    Other = 3
}
