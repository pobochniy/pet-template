namespace PetTemplate.Shared.Enums;

/// <summary>
/// Админская роль (спец. admin, 3.2). Ось отдельная от прав пространства (<see cref="PermissionEnum"/>):
/// админ — это тот, у кого есть хоть одна строка <c>UserInAdminRole</c> (3.1).
///
/// Флаговый с самого начала: строка <c>UserInAdminRole</c> держит ровно одно значение,
/// а приглашение (3.4) — набор ролей одним числом, без массивов в базе. Отсюда
/// значения — степени двойки.
///
/// Номера уезжают в базу — новые роли только в конец, следующая — <c>32</c>. Роль на «чтение»
/// и роль на «запись» у одного раздела не заводятся: ось растёт вширь, а не вглубь (3.2).
/// Набор одним числом и обратно — <see cref="AdminRoleSet"/>.
///
/// На проводе — числом, как и все enum API: своего конвертера нет, System.Text.Json
/// по умолчанию пишет число
/// </summary>
[Flags]
public enum AdminRole
{
    None = 0,

    /// <summary>Выдавать и снимать роли, приглашать админов (3.4)</summary>
    AdminManagement = 1,

    /// <summary>
    /// Поддержка аккаунтов (раздел 12): поиск, карточка, ссылка сброса пароля, освобождение
    /// почты и телефона, удаление аккаунта без пространств, журнал аккаунтов. Отдельная —
    /// ссылка сброса это вход в чужой аккаунт (3.2)
    /// </summary>
    Accounts = 2,

    /// <summary>
    /// Запись в «Расход» (спец. admin, 14): платежи поставщику, факт расхода и лимит
    /// ассистента у пространства. Смотреть сводку можно любому админу — расчёты по затратам
    /// ролью не закрываются, а запись двигает главные цифры сводки и потолок у людей.
    /// В Lad это делала роль <c>Wallets</c>; кошельков в шаблоне нет
    /// </summary>
    Billing = 4,

    /// <summary>
    /// Правка справочника моделей ассистента (спец. admin, 15): заведение, цены, порядок,
    /// включение, «Замкнуть вручную» и сверка набором фраз. Смотреть справочник можно
    /// любому админу
    /// </summary>
    Models = 8,

    /// <summary>
    /// Разбор диалогов (спец. admin, 16): чужая переписка с ассистентом и автооценка.
    /// Самая тяжёлая роль в системе — поэтому отдельная, а каждое открытие диалога
    /// пишется в журнал доступа (3.2)
    /// </summary>
    Dialogs = 16
}
