namespace PetTemplate.Shared.Enums;

/// <summary>
/// Состояние прогона — одного хода целиком (спец. assistant, 12.3).
///
/// Состояния «ждёт ответа» здесь нет и не будет: и вопрос, и показ плана
/// завершают ход, а ответ человека начинает новый (5.2, 15.2).
///
/// Номера уезжают в базу — добавлять только в конец.
/// </summary>
public enum AssistantRunStatus
{
    /// <summary>Ход исполняется</summary>
    Running = 0,

    /// <summary>Ход дошёл до ответа</summary>
    Done = 1,

    /// <summary>Человек нажал «Остановить» — частичный результат всё равно сдан</summary>
    Stopped = 2,

    /// <summary>Ход сорвался: очередь исчерпала попытки (раздел 3)</summary>
    Failed = 3
}
