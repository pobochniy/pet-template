namespace PetTemplate.Shared.Enums;

/// <summary>
/// Вид факта памяти (спец. assistant, 12.5) — ровно три разрешённые строки таблицы
/// «что храним». Просьбы о стиле ответа и тем более манера и характер человека сюда
/// не попадают вовсе: психологического портрета в продукте не будет.
///
/// Вид входит в ключ дедупликации вместе с пространством, владельцем и <c>Key</c>.
///
/// Номера уезжают в базу — добавлять только в конец.
/// </summary>
public enum AssistantFactKind
{
    /// <summary>Псевдоним или устная договорённость: «Илья» — это Илья Петров</summary>
    Alias = 0,

    /// <summary>Регулярное обстоятельство, которого нет в данных пространства: отчёт по пятницам</summary>
    Routine = 1,

    /// <summary>Умолчание, выведенное из прошлых дел: встречи обычно на час</summary>
    Default = 2
}
