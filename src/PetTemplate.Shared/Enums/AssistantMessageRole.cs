namespace PetTemplate.Shared.Enums;

/// <summary>
/// Роль сообщения в треде ассистента (спец. assistant, 12.2).
///
/// Ролей ровно три: в треде лежит только то, что человек видел на экране, —
/// промежуточные вызовы инструментов живут в трассе прогона (13.1),
/// у которой и срок жизни, и доступ другие.
///
/// Номера уезжают в базу — добавлять только в конец, освободившийся номер
/// не переиспользовать.
/// </summary>
public enum AssistantMessageRole
{
    /// <summary>Реплика человека</summary>
    User = 0,

    /// <summary>Ответ ассистента</summary>
    Assistant = 1,

    /// <summary>
    /// Резюме компакции (12.4): в модель едет вместо свёрнутой части треда,
    /// в ленте человек по-прежнему видит свою переписку целиком
    /// </summary>
    Summary = 2
}
