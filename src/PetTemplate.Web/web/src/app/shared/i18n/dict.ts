/**
 * Форма словаря после кодогена: плоская карта «ключ целиком → строка либо
 * набор форм для числа».
 *
 * Плоская, а не вложенная, хотя в `i18n/*.json` ключи лежат деревом: вложенность
 * нужна человеку, который правит файл, а `t()` нужен один доступ по ключу.
 * Разворачивает дерево кодоген — один раз при сборке, а не на каждый вызов.
 */

/**
 * Формы строки с числом. `other` обязателен во всех языках: `Intl.PluralRules`
 * отдаёт именно его для всего, что не попало в остальные категории, и он же
 * остаётся страховкой, когда категория в словарь не попала
 */
export type PluralForms = Readonly<{ other: string }> &
  Readonly<Partial<Record<Intl.LDMLPluralRule, string>>>;

export type DictEntry = string | PluralForms;

export type Dict = Readonly<Record<string, DictEntry>>;
