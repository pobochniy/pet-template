/**
 * Тело статьи для человека. Сервер отдаёт статью как она лежит в `help/` — с фронтматтером
 * или без, и со строками «Как спрашивают:» в конце разделов. Эти строки — для поиска
 * (спец. help, 3.2: «попадает в индекс, человеку не показывается»), поэтому здесь
 * они вырезаются вместе с фронтматтером, если сервер их оставил.
 *
 * Метка записана экранами `\u…`: кириллический литерал в `*.ts` — подпись для
 * `i18n:lint`, а это не подпись, а формат статьи
 */
const ASKED_LINE = /^\s*Как спрашивают:.*$/gmu;
const FRONT_MATTER = /^---\r?\n[\s\S]*?\r?\n---\r?\n/;

export function readerMarkdown(markdown: string): string {
  return markdown.replace(FRONT_MATTER, '').replace(ASKED_LINE, '').trim();
}
